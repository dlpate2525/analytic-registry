export async function run(t) {
  const { page, check, state } = t;
  const count = Number(await page.locator('.metric').filter({ hasText: 'My workspaces' }).locator('strong').innerText());
  await t.action('Follow Dashboard My workspaces', () => page.getByRole('link', { name: /My workspaces/ }).click());
  await page.getByRole('heading', { name: 'Workspaces', exact: true }).waitFor();
  check('Dashboard count matches its workspace destination', count === await page.locator('main tbody tr').count());
  check('Workspace list has five columns', await page.locator('main th').count() === 5);
  await t.action('Filter Tableau then use global workspace search', async () => {
    await page.getByLabel('Platform filter', { exact: true }).selectOption('Tableau');
    await page.getByLabel('Find a workspace', { exact: true }).fill('Mortgage');
    await page.getByLabel('Find a workspace', { exact: true }).press('Enter');
    await page.waitForURL(/q=Mortgage/);
    await page.waitForFunction(() => document.querySelector('input[aria-label="Search workspaces…"]')?.value === 'Mortgage');
  });
  check('Global search replaces old workspace filters', await page.getByLabel('Platform filter', { exact: true }).inputValue() === 'All platforms' && await page.locator('main tbody tr').count() === 1);
  await t.action('Use browser Back and reload the selected filter', async () => {
    await page.goBack(); await page.waitForURL(/platform=Tableau/);
    await page.waitForFunction(() => document.querySelector('select[aria-label="Platform filter"]')?.value === 'Tableau');
    await page.reload(); await page.waitForLoadState('networkidle');
  });
  check('Back and reload retain URL workspace filters', await page.getByLabel('Platform filter', { exact: true }).inputValue() === 'Tableau' && await page.getByLabel('Workspace scope', { exact: true }).inputValue() === 'My workspaces');
  await t.visit('/workspaces/WS-001');
  check('Workspace detail has five tabs', await page.locator('main .tabs button').count() === 5);
  await t.visit('/workspaces/WS-001?tab=Connections');
  check('Legacy Connections deep link reaches the merged tab', await page.locator('main .tabs button.active').innerText() === 'Assets & connections');
  const original = await state();
  const fixture = structuredClone(original);
  fixture.workspaces.find(row => row.id === 'WS-001').observedDate = new Date().toLocaleDateString('en-CA');
  fixture.workspaces.find(row => row.id === 'WS-001').observationComplete = true;
  fixture.evidencePolicies = { [fixture.workspaces.find(row => row.id === 'WS-001').platform]: 31 };
  fixture.connections[0].technology = ' Extract ';
  await t.fixture('Synthetic current inventory, explicit 31-day fixture policy, and legacy Extract technology; source facts otherwise unchanged', fixture);
  const technology = await page.locator('tbody tr').filter({ hasText: 'CON-001' }).first().locator('td').nth(2).innerText();
  check('Legacy Extract identifies processing without inventing technology', technology === 'Undefined\nExtract processing recorded; source technology not supplied');
  check('Displaying connection technology preserves the raw value', (await state()).connections[0].technology === ' Extract ');
  await t.visit('/workspaces/WS-001');
  const summary = await page.locator('.evidence-summary').innerText();
  check('Overview identifies inventory scope', summary.includes('Workspace inventory evidence') && summary.includes('Inventory status\nCurrent') && !summary.includes('Ready'));
  await t.action('Inspect Access & configuration', () => page.getByRole('tab', { name: 'Access & configuration', exact: true }).click());
  await page.getByText('Access dataset coverage is not recorded', { exact: false }).first().waitFor();
  check('Inventory does not establish access readiness', (await page.locator('main').innerText()).includes('Access dataset coverage is not recorded'));
  await t.action('Switch to Administrator', () => page.getByLabel('Application view').selectOption('Administrator'));
  await t.visit('/workspaces?scope=mine');
  const adminIds = await page.locator('main tbody a.strong-link').evaluateAll(rows => rows.map(row => row.getAttribute('href').split('/').at(-1)));
  check('Administrator My workspaces uses the active profile and hides retired records', JSON.stringify(adminIds.sort()) === JSON.stringify(['WS-002', 'WS-003']));
  await page.getByText('More filters', { exact: true }).click();
  await t.action('Include retired workspaces for the current profile', () => page.getByLabel('Include retired', { exact: true }).click());
  await page.waitForURL(/retired=include/);
  await page.waitForFunction(() => document.querySelectorAll('main tbody a.strong-link').length === 3);
  const withRetired = await page.locator('main tbody a.strong-link').evaluateAll(rows => rows.map(row => row.getAttribute('href').split('/').at(-1)));
  check('Include retired adds only the assigned retired workspace', JSON.stringify(withRetired.sort()) === JSON.stringify(['WS-002', 'WS-003', 'WS-011']));
  await t.visit('/');
  const registered = Number(await page.locator('.metric').filter({ hasText: /^Registered workspaces/ }).locator('strong').innerText());
  await t.action('Follow Registered workspaces and include retired', async () => {
    await page.getByRole('link', { name: /Registered workspaces/ }).click();
    await page.getByRole('heading', { name: 'Workspaces', exact: true }).waitFor();
  });
  check('Registered count matches its destination', registered === await page.locator('main tbody tr').count());
  await page.getByText('More filters', { exact: true }).click();
  await page.getByLabel('Include retired', { exact: true }).click();
  await page.waitForURL(/retired=include/);
  await page.waitForFunction(() => document.querySelector('.more-filters input[type="checkbox"]')?.checked === true);
  check('Including retired retains registration scope', page.url().includes('registry=Registered') && await page.locator('main tbody tr').count() === registered + 1);
  await t.action('Clear visible and hidden filters', () => page.getByRole('button', { name: 'Clear filters', exact: true }).click());
  await page.waitForFunction(() => !location.hash.includes('registry=') && document.querySelectorAll('main tbody tr').length === 11 && document.querySelector('.more-filters input[type="checkbox"]')?.checked === false);
  check('Clear filters removes hidden registration restriction', await page.locator('main tbody tr').count() === 11 && !(await page.getByLabel('Include retired').isChecked()));
  await page.setViewportSize({ width: 1024, height: 768 });
  await page.waitForFunction(() => Math.abs(document.querySelector('.canvas-frame').getBoundingClientRect().width - 1024) < 1);
  check('Canvas scales while keeping 1366 by 768 design coordinates', await page.locator('.canvas-frame').evaluate(element => element.clientWidth === 1366 && element.clientHeight === 768));
  await t.snapshot('scaled-canvas');
  await page.setViewportSize({ width: 1366, height: 768 });
}
